  @runs @mask
        |> String.split("\n", trim: true)
        |> Enum.with_index()
        |> Enum.flat_map(fn {hex, y} ->
          bits = for <<bit::1 <- Base.decode16!(hex, case: :lower)>>, do: bit

          bits
          |> Enum.with_index()
          |> Enum.chunk_by(fn {bit, _x} -> bit end)
          |> Enum.filter(&match?([{1, _x} | _rest], &1))
          |> Enum.map(fn [{1, x} | _rest] = run -> {x, y, length(run)} end)
        end)

  # Each run of land is one segment dashed with zero-length round-capped dashes
  # one unit apart, which draws one dot per cell.
  @path Enum.map_join(@runs, fn
          {x, y, 1} -> "M#{x + 0.5} #{y + 0.5}h0.01"
          {x, y, length} -> "M#{x + 0.5} #{y + 0.5}h#{length - 1}"
        end)

  def width, do: @columns
  def height, do: @rows

  @doc "The SVG path data that draws every land dot."
  def path, do: @path

  @doc "Projects a latitude and longitude onto the map, or nil when either is missing."
  def project(lat, lon) when is_number(lat) and is_number(lon) do
    x = (lon + 180) / @step
    y = (@top - lat) / @step

    [round_to(clamp(x, 0, @columns)), round_to(clamp(y, 0, @rows))]
  end

  def project(_lat, _lon), do: nil

  defp clamp(value, min, max), do: value |> max(min) |> min(max)

  defp round_to(value), do: Float.round(value * 1.0, 2)
